create table if not exists public.learning_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade default auth.uid(),
  log_date date not null,
  content text not null check (char_length(trim(content)) > 0),
  minutes integer not null check (minutes between 1 and 1440),
  stuck text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists learning_logs_user_date_idx
  on public.learning_logs (user_id, log_date desc, created_at desc);

alter table public.learning_logs enable row level security;

grant select, insert, delete on table public.learning_logs to authenticated;
grant usage, select on sequence public.learning_logs_id_seq to authenticated;

drop policy if exists "Users can read their own learning logs" on public.learning_logs;
create policy "Users can read their own learning logs"
  on public.learning_logs for select to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Users can create their own learning logs" on public.learning_logs;
create policy "Users can create their own learning logs"
  on public.learning_logs for insert to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete their own learning logs" on public.learning_logs;
create policy "Users can delete their own learning logs"
  on public.learning_logs for delete to authenticated
  using ((select auth.uid()) = user_id);
